// M1 throw checks, run headless through the scenario runner with real Rapier.
// These measure the throw mapping as implemented; they are not playtests.
// A report of every run is written to docs/reports/throws.md.

import { describe, expect, it, afterAll } from 'vitest';
import { mkdirSync, writeFileSync } from 'node:fs';
import { runThrow } from '../src/dev/scenario.js';
import { PHRASE } from '../src/letters/letters.js';

const rows = [];
const fmt = (n) => n.toFixed(2);
function record(name, r) {
  rows.push(
    `| ${name} | ${r.letter} | ${r.plan.kind} | ${fmt(r.plan.power)} | ${r.plan.target ? `${fmt(r.plan.target.x)}, ${fmt(r.plan.target.y)}` : ''} | ${r.wallHit ? `${fmt(r.wallHit.x)}, ${fmt(r.wallHit.y)}` : 'none'} | ${r.flightTime ? fmt(r.flightTime) : ''} | ${fmt(r.rest.x)}, ${fmt(r.rest.y)}, ${fmt(r.rest.z)} | ${r.status} |`,
  );
  return r;
}

const FULL = { vx: 0, vy: -3.5 }; // a firm upward flick, above fullSpeed
const aims = [
  { x: 0, y: 2.5 },
  { x: -4, y: 3.5 },
  { x: 4, y: 1.2 },
  { x: 2, y: 4.2 },
  { x: -2, y: 0.8 },
];

describe('full-power throws land near the aim point', () => {
  for (let id = 0; id < PHRASE.length; id++) {
    const aim = aims[id % aims.length];
    it(`${PHRASE[id]} (letter ${id}) aimed at (${aim.x}, ${aim.y})`, async () => {
      const r = record(`full power, letter ${id}`, await runThrow({ letterId: id, aim, pointer: FULL }));
      expect(r.plan.kind).toBe('throw');
      expect(r.wallHit).not.toBeNull();
      expect(Math.hypot(r.wallHit.x - r.plan.target.x, r.wallHit.y - r.plan.target.y)).toBeLessThan(0.4);
    });
  }
});

describe('power depends on flick speed', () => {
  it('weaker flicks with the same aim hit lower or fall short', async () => {
    const aim = { x: 0, y: 3 };
    const strong = record('flick 3.5 H/s', await runThrow({ letterId: 2, aim, pointer: { vx: 0, vy: -3.5 } }));
    const medium = record('flick 1.8 H/s', await runThrow({ letterId: 2, aim, pointer: { vx: 0, vy: -1.8 } }));
    const weak = record('flick 1.0 H/s', await runThrow({ letterId: 2, aim, pointer: { vx: 0, vy: -1.0 } }));
    expect(strong.wallHit.y).toBeGreaterThan(medium.wallHit?.y ?? -1);
    expect(weak.wallHit === null || weak.wallHit.y < (medium.wallHit?.y ?? 0)).toBe(true);
  });

  it('a slow release is a drop that lands on the table near the hand', async () => {
    const r = record('slow release', await runThrow({ letterId: 4, aim: { x: 0, y: 2 }, pointer: { vx: 0.1, vy: -0.2 } }));
    expect(r.plan.kind).toBe('drop');
    expect(r.wallHit).toBeNull();
    expect(r.rest.y).toBeLessThan(0.6);
    expect(r.rest.z).toBeGreaterThan(-6.5);
  });
});

describe('spin comes from the sideways part of the flick', () => {
  it('flicking right spins clockwise as seen from the camera, left spins the other way', async () => {
    const right = record('flick up-right', await runThrow({ letterId: 2, aim: { x: 0, y: 2.5 }, pointer: { vx: 1.5, vy: -3 } }));
    const left = record('flick up-left', await runThrow({ letterId: 2, aim: { x: 0, y: 2.5 }, pointer: { vx: -1.5, vy: -3 } }));
    expect(right.plan.spin).toBeLessThan(0);
    expect(left.plan.spin).toBeGreaterThan(0);
  });
});

describe('determinism', () => {
  it('the same throw from the same seed lands in the same place', async () => {
    const spec = { letterId: 5, aim: { x: 1, y: 2 }, pointer: { vx: 0.4, vy: -2.8 } };
    const a = await runThrow(spec);
    const b = await runThrow(spec);
    expect(a.rest).toEqual(b.rest);
  });
});

afterAll(() => {
  mkdirSync('docs/reports', { recursive: true });
  writeFileSync(
    'docs/reports/throws.md',
    [
      '# Throw scenario report',
      '',
      'Generated by `npm test` (test/throws.test.js) with the scenario runner, real Rapier, seed 1.',
      'Measurements of the current mapping, not playtest results. Coordinates in card heights; wall face at z = -12.',
      '',
      '| run | letter | kind | power | aim (x, y) | wall hit (x, y) | flight s | rest (x, y, z) | status |',
      '|---|---|---|---|---|---|---|---|---|',
      ...rows,
      '',
    ].join('\n'),
  );
});
